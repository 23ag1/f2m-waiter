-- ============================================================================
-- AI Broadcast Demo — схема БД + seed данные для демонстрации
-- ============================================================================

-- ----- Таблица профилей пользователей -----
CREATE TABLE IF NOT EXISTS profile (
    user_id       BIGINT PRIMARY KEY,
    fio           TEXT,
    phone         TEXT,
    age           TEXT,       -- хранится как диапазон: 'до 18' | '18-25' | '26-35' | '36-45' | '46-55' | '56+'
    sex           TEXT,       -- 'Мужчина' | 'Женщина' | NULL
    style         TEXT,       -- 'диетическое' | 'стандартное' | 'веганство' | 'вегетарианство'
    kcal          TEXT,
    prefer        TEXT,       -- что любит (свободный текст)
    hate          TEXT,       -- что не любит / на что аллергия
    mood          TEXT,       -- текущее настроение
    hungry        TEXT,
    experiments   TEXT,       -- готов ли пробовать новое
    reviews       TEXT,
    partner_id    TEXT
);

-- ----- История заказов (нужна для фильтра "последнее посещение") -----
CREATE TABLE IF NOT EXISTS orders_history (
    id          SERIAL PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    dish        TEXT,
    created_at  TIMESTAMP DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_orders_history_user_id   ON orders_history(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_history_created   ON orders_history(created_at);

-- ----- Лог рассылок (создаётся также автоматически сервисом) -----
CREATE TABLE IF NOT EXISTS broadcast_log (
    id               SERIAL PRIMARY KEY,
    admin_request    TEXT NOT NULL,
    model            TEXT NOT NULL DEFAULT 'deepseek',
    filters          JSONB DEFAULT '{}',
    recipients_count INTEGER DEFAULT 0,
    sent_count       INTEGER DEFAULT 0,
    skipped_count    INTEGER DEFAULT 0,
    created_at       TIMESTAMP DEFAULT NOW()
);

